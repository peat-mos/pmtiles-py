from peat_mos.pmtiles import _spec

_ORIGIN = _spec.Position(0.0, 0.0)


def header(
    *,
    version: int = _spec.VERSION,
    root_directory_offset: int = 127,
    root_directory_length: int = 10,
    metadata_offset: int = 200,
    metadata_length: int = 0,
    leaf_directories_offset: int = 300,
    leaf_directories_length: int = 0,
    tile_data_offset: int = 400,
    tile_data_length: int = 100,
    number_of_addressed_tiles: int = 1,
    number_of_tile_entries: int = 1,
    number_of_tile_contents: int = 1,
    clustered: bool = True,
    internal_compression: _spec.Compression = _spec.Compression.GZIP,
    tile_compression: _spec.Compression = _spec.Compression.GZIP,
    tile_type: _spec.TileType = _spec.TileType.MVT,
    min_zoom: int = 0,
    max_zoom: int = 5,
    min_position: _spec.Position = _ORIGIN,
    max_position: _spec.Position = _ORIGIN,
    center_zoom: int = 0,
    center_position: _spec.Position = _ORIGIN,
) -> _spec.Header:
    return _spec.Header(
        version=version,
        root_directory_offset=root_directory_offset,
        root_directory_length=root_directory_length,
        metadata_offset=metadata_offset,
        metadata_length=metadata_length,
        leaf_directories_offset=leaf_directories_offset,
        leaf_directories_length=leaf_directories_length,
        tile_data_offset=tile_data_offset,
        tile_data_length=tile_data_length,
        number_of_addressed_tiles=number_of_addressed_tiles,
        number_of_tile_entries=number_of_tile_entries,
        number_of_tile_contents=number_of_tile_contents,
        clustered=clustered,
        internal_compression=internal_compression,
        tile_compression=tile_compression,
        tile_type=tile_type,
        min_zoom=min_zoom,
        max_zoom=max_zoom,
        min_position=min_position,
        max_position=max_position,
        center_zoom=center_zoom,
        center_position=center_position,
    )
